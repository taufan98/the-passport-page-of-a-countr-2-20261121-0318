#!/usr/bin/env python3
"""The Passport Page of a Country That Isn't There.

Writes one image to /output/entry.png (or $MAKEFUN_OUTPUT_DIR/entry.png):
an invented passport spread for the fictional Republic of Talvera.

Left page: the data page — portrait, holder details, issue 12 JUN 2023,
expiry 12 JUN 2033, and a machine-readable zone with ICAO check digits.
Right page: the visa page — arrival/departure stamps from Talvera's three
invented neighbours (Brevania, Karnath, Ostrovia), all dated after the
passport was issued, plus the telling paperwork detail: a visa condition
restricting travel to those three neighbours, with entry to the Northern
Marches requiring a frontier permit (Form F-7).

The image is drawn programmatically with Pillow (shapes, text, a stylised
portrait silhouette, ink stamps, MRZ strip). No network, no external
images, deterministic output. If Pillow is unavailable in the sandbox,
the program falls back to the entry.png shipped beside it in the
repository (the same image, generated by this same program), so the
entry is still written and valid.
"""

