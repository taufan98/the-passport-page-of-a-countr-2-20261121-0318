    # centre gutter shadow
    for i in range(14):
        a = 26 - i
        d.line([(512 - i, 134), (512 - i, 830)], fill=(0, 0, 0, a))
        d.line([(512 + i, 134), (512 + i, 830)], fill=(0, 0, 0, a))
