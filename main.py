def mrz_check(text):
    """ICAO 9303 check digit: weights 7, 3, 1 over 0-9, A-Z=10-35, '<'=0."""
    weights = (7, 3, 1)
    total = 0
    for i, ch in enumerate(text):
        if ch == "<":
            v = 0
        elif ch.isdigit():
            v = int(ch)
        else:
            v = ord(ch) - 55
        total += v * weights[i % 3]
    return str(total % 10)


def mrz_lines():
    line1 = "P<TALMAROVIC<<ELENA<<<<<<<<<<<<<<<<<<<<<<<"
    line1 = line1[:44].ljust(44, "<")
    doc = "TV4829167"
    doc_c = mrz_check(doc)
    dob = "940314"
    dob_c = mrz_check(dob)
    exp = "330612"
    exp_c = mrz_check(exp)
    body = doc + doc_c + "TAL" + dob + dob_c + "F" + exp + exp_c
    body = body.ljust(43, "<")
    line2 = body + mrz_check(body)
    return line1, line2


def draw():
    from PIL import Image, ImageDraw, ImageFont

    def font(path, size):
        return ImageFont.truetype(path, size)

    img = Image.new("RGB", (WIDTH, HEIGHT), DESK)
    d = ImageDraw.Draw(img, "RGBA")

    # ---- desk: soft vignette + faint table edge
