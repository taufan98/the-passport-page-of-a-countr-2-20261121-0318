    for yy in range(150, 830, 46):
        d.arc([60, yy - 120, 500, yy + 120], start=200, end=340, fill=(TEAL[0], TEAL[1], TEAL[2], 14))
        d.arc([524, yy - 120, 964, yy + 120], start=200, end=340, fill=(TEAL[0], TEAL[1], TEAL[2], 14))

    # ================================================= LEFT PAGE: data page
    # coat of arms: gull over three waves in a double circle
    cx, cy = 278, 196
    d.ellipse([cx - 30, cy - 30, cx + 30, cy + 30], outline=TEAL, width=2)
    d.ellipse([cx - 25, cy - 25, cx + 25, cy + 25], outline=GOLD, width=1)
    d.arc([cx - 18, cy - 14, cx + 18, cy + 6], start=180, end=360, fill=TEAL, width=2)
    d.arc([cx - 12, cy - 8, cx + 12, cy + 8], start=200, end=340, fill=TEAL, width=2)
    for wy in (cy + 12, cy + 18):
        d.arc([cx - 20, wy - 8, cx - 2, wy + 8], start=180, end=360, fill=TEAL, width=1)
        d.arc([cx + 2, wy - 8, cx + 20, wy + 8], start=180, end=360, fill=TEAL, width=1)

    f_title = font(SERIF_B, 30)
    f_sub = font(SANS, 13)
    f_small = font(SANS, 11)
    d.text((278, 232), "REPUBLIC OF TALVERA", font=f_title, fill=TEAL_DARK, anchor="ma")
    d.text((278, 266), "REPUBLIKA TALVERA  ·  PASSPORT  ·  PUTOVNICA", font=f_sub, fill=INK_SOFT, anchor="ma")
    d.line([(70, 292), (486, 292)], fill=GOLD, width=2)
    d.line([(70, 296), (486, 296)], fill=GOLD, width=1)

    # ---- portrait (stylised official photo, duotone)
    px0, py0, px1, py1 = 70, 312, 224, 492
    d.rectangle([px0, py0, px1, py1], fill=(206, 198, 178), outline=TEAL, width=2)
    d.rectangle([px0 + 4, py0 + 4, px1 - 4, py1 - 4], outline=GOLD, width=1)
    # backdrop gradient bands
    for i in range(py1 - py0 - 8):
        t = i / max(1, (py1 - py0 - 9))
        c = tuple(int(168 + (120 - 168) * t) if k == 0 else int(178 + (140 - 178) * t) if k == 1 else int(160 + (128 - 160) * t) for k in range(3))
        d.line([(px0 + 5, py0 + 5 + i), (px1 - 5, py0 + 5 + i)], fill=c)
    # shoulders / garment
    d.polygon([(78, 488), (216, 488), (196, 428), (98, 428)], fill=(31, 77, 74))
    d.polygon([(98, 428), (196, 428), (178, 452), (116, 452)], fill=(24, 60, 58))
    # embroidered collar: small gold chevrons
    for cxp in range(112, 184, 12):
        d.polygon([(cxp, 442), (cxp + 6, 452), (cxp + 12, 442)], outline=GOLD, width=1)
    # neck + face
    d.rectangle([138, 400, 156, 434], fill=SKIN_DARK)
    d.ellipse([118, 336, 176, 410], fill=SKIN)
    # hair: cap + bun, dark brown
    d.pieslice([114, 330, 180, 392], start=180, end=360, fill=HAIR)
    d.ellipse([138, 318, 168, 344], fill=HAIR)  # bun
    d.arc([118, 336, 176, 396], start=180, end=300, fill=HAIR, width=10)
