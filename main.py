    d.arc([126, 364, 140, 370], start=200, end=340, fill=(60, 40, 26), width=1)
    d.arc([154, 364, 168, 370], start=200, end=340, fill=(60, 40, 26), width=1)
    d.ellipse([129, 373, 135, 377], fill=(40, 28, 20))
    d.ellipse([159, 373, 165, 377], fill=(40, 28, 20))
    d.line([(146, 380), (146, 388)], fill=SKIN_DARK, width=1)
    d.line([(141, 396), (153, 396)], fill=(150, 80, 70), width=2)
    # soft cheek shading
    d.ellipse([124, 386, 132, 392], fill=(205, 150, 120))
